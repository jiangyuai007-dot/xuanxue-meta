/** 动爻变爻关系：以本爻地支与变爻地支的五行论回头生克 */
const ZHI_WX = {
  子: '水', 丑: '土', 寅: '木', 卯: '木', 辰: '土', 巳: '火',
  午: '火', 未: '土', 申: '金', 酉: '金', 戌: '土', 亥: '水',
};
const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
const KE = { 木: '土', 火: '金', 土: '水', 金: '木', 水: '火' };

/** 变爻对本爻的作用：回头生 / 回头克 / 泄气 / 比和 */
export function bianRel(benZhi, bianZhi) {
  const a = ZHI_WX[benZhi];
  const b = ZHI_WX[bianZhi];
  if (!a || !b) return '';
  if (SHENG[b] === a) return `变爻${bianZhi}（${b}）回头生本爻${benZhi}（${a}）——先难后易，外力来助`;
  if (KE[b] === a) return `变爻${bianZhi}（${b}）回头克本爻${benZhi}（${a}）——事有后患，宜防收尾生变`;
  if (SHENG[a] === b) return `变爻${bianZhi}（${b}）泄本爻${benZhi}（${a}）之气——付出多而回报慢`;
  if (KE[a] === b) return `本爻${benZhi}（${a}）克变爻${bianZhi}（${b}）——主动可控，代价由自己承担`;
  return `变爻${bianZhi}与本爻${benZhi}同气——力量延续，事态平稳过渡`;
}

/** 动爻阴阳进退：以本爻地支与变爻地支的顺逆关系近似论进神 / 退神 */
const ZHI_ORDER = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];
export function dongTrend(benZhi, bianZhi) {
  const from = ZHI_ORDER.indexOf(benZhi);
  const to = ZHI_ORDER.indexOf(bianZhi);
  if (from < 0 || to < 0) return '';
  if (to === from) return '动而化同，力量原地打转，宜主动破局';
  const forward = ((to - from) + 12) % 12 <= 6;
  return forward ? '动而化进：事态向前推进，宜趁势而为' : '动而化退：事态回缩，宜见好就收或暂缓';
}

/** 世爻旺衰判词 */
export function shiWord(shi) {
  if (!shi) return '世爻信息不足，宜结合卦象整体判断。';
  return ['旺', '相'].includes(shi.wangshuai)
    ? `世爻${shi.wangshuai}，自身条件具备推进的基础：底气足、可主动；但旺者易过刚，宜留商量余地。`
    : `世爻${shi.wangshuai}，自身力量偏弱：宜借力、宜等时，不宜硬扛；先把条件补齐比抢时间更重要。`;
}

/** 用神旺衰判词 */
export function ysWord(name, lines) {
  if (!lines || !lines.length) return `卦中未见${name}，传统上谓之「用神不上卦」，多主此事条件未显，或从伏神、日月另寻线索`;
  const strong = lines.some((l) => ['旺', '相'].includes(l.wangshuai));
  const kong = lines.some((l) => l.xunkong);
  const yuePo = lines.some((l) => l.yuePo);
  const parts = [];
  parts.push(strong ? `用神${name}得月令之气（${lines.map((l) => l.wangshuai).join('、')}），力量偏强` : `用神${name}在月令处偏弱（${lines.map((l) => l.wangshuai).join('、')}），需待时日或借外力`);
  if (kong) parts.push('用神落空亡：主事体有落空、延后或信息不全之象，宜把时间与交付方式落实清楚');
  if (yuePo) parts.push('用神被月建冲破：主外力干扰、计划被打断，宜预留缓冲');
  return `${parts.join('；')}。`;
}

/** 动爻所主之事（以六亲为纲） */
export function dongYi(liuqin) {
  const d = LIUQIN[liuqin];
  if (!d) return '关键变化点需结合六亲与用神综合判断';
  return `${d.shi}`;
}

