/** 命宫三方四正：命宫、财帛（+4）、官禄（+8）、迁移（+6） */
export function sanFangSiZheng(zhiIndex, n = 12) {
  return [0, 4, 8, 6].map((off) => (zhiIndex + off) % n);
}

/** 常见格局判定（只做「三方四正是否有此组星」的机械判定，不给过度断言） */
export function detectPatterns(f) {
  const out = [];
  const idxToPalace = {};
  for (const p of Object.values(f.palaces || {})) idxToPalace[p.zhiIndex] = p;
  const starAt = (zhiIndex) => (idxToPalace[zhiIndex]?.stars || []).map((s) => s.name);
  const sfsz = sanFangSiZheng(f.mingGong.zhiIndex).map(starAt).flat();

  const has = (n) => sfsz.includes(n);
  if (has('七杀') && has('破军') && has('贪狼')) {
    out.push({ name: '杀破狼格', text: '命宫三方四正会齐七杀、破军、贪狼：这是「动」的格局——一生变动多、起伏大，宜在变动中找机会，不宜求稳；好处是能折腾出局面，代价是安定感来得晚。' });
  }
  if (has('天机') && has('太阴') && has('天同') && has('天梁')) {
    out.push({ name: '机月同梁格', text: '命宫三方四正会天机、太阴、天同、天梁：这是「谋」的格局——靠脑力与专业立身，宜在稳定体系内做技术或顾问，忌孤注一掷式的冒险。' });
  }
  if (has('紫微') && has('天府')) {
    out.push({ name: '紫府同宫格', text: '命宫三方四正见紫微与天府同会：这是「厚」的格局——自尊与守成并重，宜掌权掌财，忌格局太小把自己困住。' });
  }
  if (has('太阳') && has('太阴')) {
    out.push({ name: '日月同临格', text: '命宫三方四正见太阳与太阴：明暗相济，主既能被看见也能静得下来，宜走「台前 + 幕后」双轨的路线。' });
  }
  if (has('巨门') && has('太阳')) {
    out.push({ name: '巨日同宫格', text: '命宫三方四正见巨门与太阳：口才与名声相生，宜靠说理与传播立身；忌口舌招怨，宜把锋芒放进专业里。' });
  }
  if (has('廉贞') && has('贪狼')) {
    out.push({ name: '廉贞贪狼格', text: '命宫三方四正见廉贞与贪狼：才情与欲望并行，宜把审美与交际变成生产力；忌沉溺与投机。' });
  }
  return out;
}

/** 星曜落宫的断语（星性 × 宫位） */
export function starInPalace(starName, palaceName) {
  const s = STAR[starName];
  const p = PALACE[palaceName];
  if (!s || !p) return '';
  return `${starName}在${palaceName}：${s.xing}——${palaceName}${p.slice(0, 0)}${s.shi}这一层，落于此宫的表现是「${s.ye}」。此宫本身主${p}。`;
}

/** 四化落宫的断语 */
export function huaInPalace(huaKey, starName, palaceName) {
  const s = STAR[starName];
  const h = HUA[huaKey];
  const p = PALACE[palaceName];
  if (!h) return '';
  const star = s ? `${starName}（${s.xing.split('、')[0]}）` : starName;
  return `${h.yi}。落点在${starName}·${palaceName || '—'}——${star}的${s ? s.shi : '事象'}，与「${palaceName || '—'}」${p ? `（${p}）` : ''}叠在一起看：这一宫是你这一生要反复用力之处。`;
}
