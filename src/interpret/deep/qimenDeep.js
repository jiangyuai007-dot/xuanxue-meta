/** 十二长生判词（奇门宫位力量） */
export function csWord(state, note) {
  if (!state) return '';
  return `${state}${note ? `：${note}` : ''}`;
}

/** 宫位综合断语：门 + 星 + 神 三合一 */
export function palaceRead(p) {
  const d = DOOR[p.door];
  const s = STAR[p.star];
  const g = SHEN[p.shen];
  const parts = [];
  if (d) parts.push(`${p.door}——${d.yi}。${d.yi2}`);
  if (s) parts.push(`${p.star}——${s.xing}`);
  if (g) parts.push(`${p.shen}——${g.xing}`);
  return parts.join(' ');
}

/** 宫位吉凶定调 */
export function palaceTone(p) {
  const d = DOOR[p.door];
  const s = STAR[p.star];
  const good = (d?.ji === '吉' ? 1 : 0) + (s?.ji === '吉' ? 1 : 0);
  const bad = (d?.ji === '凶' ? 1 : 0) + (s?.ji === '凶' ? 1 : 0);
  let t;
  if (good >= 2) t = '门星皆吉，此宫可作首选';
  else if (good === 1 && bad === 0) t = '门吉星平，此宫可用';
  else if (bad >= 2) t = '门星皆不吉，此宫宜避';
  else if (bad === 1 && good === 0) t = '门星偏凶，此宫宜缓';
  else t = '吉凶相杂，此宫宜权衡后使用';
  if (p.kongWang) t += '；又值空亡，力量打折、应事偏迟';
  if (p.maXing) t += '；又临马星，主动与出行';
  if (p.ruMu) t += '；又入墓，主事被收束、暂不宜动';
  if (p.menPo) t += '；又门迫，吉门减力';
  if (p.jiXing) t += '；又击刑，主刑伤与急变';
  return t + '。';
}
