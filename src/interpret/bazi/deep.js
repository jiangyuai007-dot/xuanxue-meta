/** 把一条干支作用关系转成「白话断语」；返回 '' 表示该类型无对应库 */
export function relYi(r) {
  const t = r?.type || '';
  const name = r?.name || '';
  const keys = safeList(r?.keys);
  if (t === 'chong') {
    const two = (name.match(/[子丑寅卯辰巳午未申酉戌亥]/g) || []).slice(0, 2);
    if (two.length === 2) return CHONG_YI[pairKey(two[0], two[1])] || `${name}：两支相冲，主动荡与变动`;
    return `${name}：相冲主动`;
  }
  if (t === 'he' || t === 'banhe') {
    const two = (name.match(/[子丑寅卯辰巳午未申酉戌亥]/g) || []).slice(0, 2);
    if (two.length === 2) return HE_YI[pairKey(two[0], two[1])] || (BANHE_YI[two.join('')] || `${name}`);
    return `${name}`;
  }
  if (t === 'xing') {
    const zs = (name.match(/[子丑寅卯辰巳午未申酉戌亥]/g) || []);
    if (zs.length >= 3) return XING_YI[[...new Set(zs)].sort().join('')] || `${name}：相刑主纠缠内耗`;
    if (zs.length === 2 && zs[0] === zs[1]) return XING_YI[zs[0] + zs[0]] || `${name}：自刑主自我较劲`;
    if (zs.length === 2) return XING_YI[pairKey(zs[0], zs[1])] || `${name}：相刑主纠缠`;
    return `${name}：相刑主纠缠内耗`;
  }
  if (t === 'hai') {
    const two = (name.match(/[子丑寅卯辰巳午未申酉戌亥]/g) || []).slice(0, 2);
    if (two.length === 2) return HAI_YI[pairKey(two[0], two[1])] || `${name}：相害主暗损`;
    return `${name}：相害主暗损`;
  }
  if (t === 'sanhe') {
    const k = (name.match(/[子丑寅卯辰巳午未申酉戌亥]/g) || []).sort().join('');
    for (const kk of Object.keys(SANHE_YI)) if ([...kk].sort().join('') === k) return SANHE_YI[kk];
    return `${name}：三合聚气`;
  }
  if (t === 'sanhui') {
    const k = (name.match(/[子丑寅卯辰巳午未申酉戌亥]/g) || []).sort().join('');
    for (const kk of Object.keys(SANHUI_YI)) if ([...kk].sort().join('') === k) return SANHUI_YI[kk];
    return `${name}：方局聚气`;
  }
  if (t === 'po') return `${name}：相破主破损与疏离`;
  return name ? `${name}` : '';
}

/** 关系落在哪个宫（用于「宫位语义」衔接） */
export function relGong(r) {
  const keys = safeList(r?.keys).filter((k) => k in GONG_YI);
  if (!keys.length) return null;
  return keys.map((k) => GONG_YI[k]).find(Boolean) || null;
}

