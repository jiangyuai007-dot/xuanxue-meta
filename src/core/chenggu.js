const CN_NUM = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十'];

/** 钱（整数）→ 「几两几钱」中文 */
function qianToText(q) {
  const liang = Math.floor(q / 10);
  const rem = q % 10;
  const liangTxt = liang <= 10 ? CN_NUM[liang] : String(liang);
  return rem ? `${liangTxt}两${CN_NUM[rem]}钱` : `${liangTxt}两`;
}

/**
 * 计算称骨
 * @param {{ yearGanzhi:string, lunarMonth:number, lunarDay:number, hourZhiIndex:number, hourZhi:string }} p
 *   yearGanzhi 例「庚午」；lunarMonth 农历月 1-12（闰月按本月）；lunarDay 农历日 1-30；hourZhi 时支
 */
export function computeChengGu(p) {
  const gz = String(p.yearGanzhi || '');
  const GAN = '甲乙丙丁戊己庚辛壬癸';
  const ZHI = '子丑寅卯辰巳午未申酉戌亥';
  const gi = GAN.indexOf(gz[0]);
  const zi = ZHI.indexOf(gz[1]);
  if (gi < 0 || zi < 0 || zi !== (gi % 12)) return null;

  const m = Math.min(12, Math.max(1, Number(p.lunarMonth) || 1));
  const d = Math.min(30, Math.max(1, Number(p.lunarDay) || 1));
  const h = ((Number(p.hourZhiIndex) % 12) + 12) % 12;

  const yearIdx = (() => {
    // 六十甲子序：i 满足 i%10===gi 且 i%12===zi
    for (let i = 0; i < 60; i++) if (i % 10 === gi && i % 12 === zi) return i;
    return 0;
  })();
  const wYear = YEAR_QIAN[yearIdx];
  const wMonth = MONTH_QIAN[m - 1];
  const wDay = DAY_QIAN[d - 1];
  const wHour = HOUR_QIAN[h];

  const total = wYear + wMonth + wDay + wHour;
  const verse = VERSES[total] || '';

  const CN_MONTH = ['正', '二', '三', '四', '五', '六', '七', '八', '九', '十', '冬', '腊'];
  const CN_DAY = [
    '初一', '初二', '初三', '初四', '初五', '初六', '初七', '初八', '初九', '初十',
    '十一', '十二', '十三', '十四', '十五', '十六', '十七', '十八', '十九', '二十',
    '廿一', '廿二', '廿三', '廿四', '廿五', '廿六', '廿七', '廿八', '廿九', '三十',
  ];

  return {
    totalQian: total,
    totalText: qianToText(total),
    verse,
    parts: [
      { k: '年', label: gz, qian: wYear, text: qianToText(wYear) },
      { k: '月', label: `${CN_MONTH[m - 1]}月`, qian: wMonth, text: qianToText(wMonth) },
      { k: '日', label: CN_DAY[d - 1], qian: wDay, text: qianToText(wDay) },
      { k: '时', label: `${ZHI[h]}时`, qian: wHour, text: qianToText(wHour) },
    ],
    note: '称骨为袁天罡传统民俗算法：农历年干支、月、日、时辰骨重相加，查《称骨歌》得断语',
  };
}
